#!/usr/bin/env python3
"""
Packs the art of the game for the web.

    python scripts/art.py            (or: npm run art)

The court and the character are made by the Blender scripts in
design/prueba-3d, which leave their output in design/prueba-3d/assets. This
takes that output and writes what the game downloads, into public/art:

  court/<layer>.avif   every layer of the court, as AVIF: less than half the
                       weight of the WebP with no difference to the eye
  court/<layer>.webp   the same layer as it came, for browsers without AVIF
  character.bin        the mesh, the skeleton and the clips, as they came
  character.bin.gz     the same file gzipped: hosts of static files do not
                       always compress a file they do not know, so the game
                       asks for this one first and unpacks it itself

It also rewrites the table of layers in src/render/stage/court-art.ts, which
says where each picture goes.

Needs Python 3.9+ and Pillow 11.3+ (the first with AVIF built in). Running it
again with the same input gives the same files.
"""
from __future__ import annotations

import gzip
import io
import json
import re
import shutil
import sys
from pathlib import Path

try:
    from PIL import Image, features
except ImportError:
    sys.exit('Falta Pillow: pip install "pillow>=11.3"')

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'design' / 'prueba-3d' / 'assets'
TARGET = ROOT / 'public' / 'art'
TABLE = ROOT / 'src' / 'render' / 'stage' / 'court-art.ts'

# How hard the AVIF encoder squeezes (0..100) and how long it thinks about it
# (0 slowest and smallest .. 10). At 60 the court is 134 KB instead of 313 KB
# and the pictures differ from the WebP by about one level in 255 on average.
AVIF_QUALITY = 60
AVIF_SPEED = 3


def kb(size: int) -> str:
    return f'{size / 1024:6.1f} KB'


def pack_court() -> tuple[dict, int, int]:
    source = SOURCE / 'cancha'
    meta = json.loads((source / 'cancha.json').read_text(encoding='utf-8'))
    target = TARGET / 'court'
    target.mkdir(parents=True, exist_ok=True)
    for old in target.glob('*'):
        old.unlink()

    avif_total = 0
    webp_total = 0
    for layer in meta['layers']:
        name = layer['name']
        original = source / layer['file']
        shutil.copyfile(original, target / f'{name}.webp')
        image = Image.open(original).convert('RGBA')
        packed = io.BytesIO()
        image.save(packed, 'AVIF', quality=AVIF_QUALITY, speed=AVIF_SPEED)
        (target / f'{name}.avif').write_bytes(packed.getvalue())
        avif_total += packed.tell()
        webp_total += original.stat().st_size
        print(f'  {name:8s} {image.size[0]:4d} x {image.size[1]:4d}   webp {kb(original.stat().st_size)}   avif {kb(packed.tell())}')
    return meta, avif_total, webp_total


def pack_character() -> tuple[int, int]:
    original = SOURCE / 'personaje.bin'
    data = original.read_bytes()
    if data[:4] != b'PAD1':
        sys.exit(f'{original} no es un personaje (falta la marca PAD1)')
    (TARGET / 'character.bin').write_bytes(data)
    # No name and no date inside: the same input always gives the same file.
    packed = io.BytesIO()
    with gzip.GzipFile(filename='', mode='wb', fileobj=packed, compresslevel=9, mtime=0) as out:
        out.write(data)
    (TARGET / 'character.bin.gz').write_bytes(packed.getvalue())
    return len(data), packed.tell()


def write_table(meta: dict) -> None:
    layers = '\n'.join(
        f"    {{ name: '{layer['name']}', x: {layer['x']}, y: {layer['y']}, w: {layer['w']}, h: {layer['h']} }},"
        for layer in meta['layers']
    )
    names = ' | '.join(f"'{layer['name']}'" for layer in meta['layers'])
    block = f"""// <generated by scripts/art.py>
export type LayerName = {names};

export const COURT_ART = {{
  /** Size of the whole render, in its own pixels, and how many of them make a design pixel. */
  render: [{meta['render'][0]}, {meta['render'][1]}] as [number, number],
  dpr: {meta['dpr']},
  folder: 'art/court/',
  /** Formats each picture comes in, best first. */
  formats: ['avif', 'webp'] as string[],
  layers: [
{layers}
  ] as Array<{{ name: LayerName; x: number; y: number; w: number; h: number }}>,
}};
// </generated>"""
    text = TABLE.read_text(encoding='utf-8')
    pattern = re.compile(r'// <generated by scripts/art\.py>.*?// </generated>', re.S)
    if not pattern.search(text):
        sys.exit(f'{TABLE} no tiene el bloque generado')
    TABLE.write_text(pattern.sub(lambda _: block, text), encoding='utf-8', newline='\n')


def main() -> None:
    if not features.check('avif'):
        sys.exit('Este Pillow no sabe escribir AVIF: hace falta la versión 11.3 o más nueva')
    if not SOURCE.exists():
        sys.exit(f'No está {SOURCE}')
    TARGET.mkdir(parents=True, exist_ok=True)

    print('Cancha')
    meta, avif_total, webp_total = pack_court()
    print(f'  {"total":8s}               webp {kb(webp_total)}   avif {kb(avif_total)}')
    write_table(meta)

    print('Personaje')
    raw, packed = pack_character()
    print(f'  character.bin {kb(raw)}   gzip {kb(packed)}')

    print(f'\nLo que baja un navegador de hoy: {kb(avif_total + packed)} (antes {kb(webp_total + raw)})')


if __name__ == '__main__':
    main()
