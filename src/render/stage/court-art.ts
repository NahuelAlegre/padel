import type { Assets, Picture } from '../../platform/types';

/**
 * The court as it was rendered: a club at sunset, with its light baked into
 * a few pictures, one per layer. They are layers because the players are
 * drawn in between them and because each one moves differently when the
 * camera does.
 *
 * The pictures were rendered from the reference camera for a 390 x 844 frame
 * with some room around it. `x`, `y`, `w` and `h` say which part of that
 * render a picture holds, in pixels of the render. The file itself may be
 * smaller than that (the sky, which is soft, is stored at half size): it is
 * stretched over its place.
 *
 * The table below is written by `scripts/art.py` from the output of the
 * Blender scripts in design/prueba-3d, together with the pictures themselves.
 * Do not edit it by hand.
 */
// <generated by scripts/art.py>
export type LayerName = 'cielo' | 'piso' | 'entorno' | 'paredes' | 'red' | 'cerca' | 'frente';

export const COURT_ART = {
  /** Size of the whole render, in its own pixels, and how many of them make a design pixel. */
  render: [874, 2026] as [number, number],
  dpr: 2,
  folder: 'art/court/',
  /** Formats each picture comes in, best first. */
  formats: ['avif', 'webp'] as string[],
  layers: [
    { name: 'cielo', x: 0, y: 0, w: 874, h: 1012 },
    { name: 'piso', x: 0, y: 708, w: 874, h: 1318 },
    { name: 'entorno', x: 0, y: 244, w: 874, h: 1087 },
    { name: 'paredes', x: 36, y: 706, w: 802, h: 768 },
    { name: 'red', x: 170, y: 1034, w: 533, h: 53 },
    { name: 'cerca', x: 46, y: 1296, w: 782, h: 178 },
    { name: 'frente', x: 44, y: 1568, w: 148, h: 81 },
  ] as Array<{ name: LayerName; x: number; y: number; w: number; h: number }>,
};
// </generated>

/** One layer, loaded: its picture and where it goes, in design pixels from the centre of the frame. */
export interface CourtLayer {
  name: LayerName;
  image: Picture;
  dx: number;
  dy: number;
  dw: number;
  dh: number;
}

export type CourtLayers = Record<LayerName, CourtLayer>;

/** The near back wall is drawn fainter than it was rendered, so it does not hide the player behind it. */
export const NEAR_WALL_ALPHA = 0.7;

/** Loads every layer of the court. Fails if any of them is missing. */
export async function loadCourt(assets: Assets): Promise<CourtLayers> {
  const { render, dpr, folder, formats, layers } = COURT_ART;
  const images = await Promise.all(
    layers.map((layer) => assets.image(formats.map((format) => `${folder}${layer.name}.${format}`))),
  );
  const out = {} as CourtLayers;
  layers.forEach((layer, i) => {
    out[layer.name] = {
      name: layer.name,
      image: images[i]!,
      dx: (layer.x - render[0] / 2) / dpr,
      dy: (layer.y - render[1] / 2) / dpr,
      dw: layer.w / dpr,
      dh: layer.h / dpr,
    };
  });
  return out;
}
